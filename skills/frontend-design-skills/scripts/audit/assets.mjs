// Asset audit: source trails, broken files, credits, duplicate media.

import { finding, SEVERITY } from '../lib/rules.mjs';

export const id = 'assets';
export const label = 'Assets';

const VALID_SOURCES = new Set(['client', 'commissioned', 'phone', 'supplier', 'illustration', 'library', 'stand-in', 'wikimedia', 'unsplash']);
const LIBRARY_SOURCES = new Set(['library', 'stand-in', 'wikimedia', 'unsplash']);

export async function audit(ctx) {
  const { facts } = ctx;
  const findings = [];
  const seen = new Map();

  for (const image of facts.images.filter(img => img.displayed)) {
    // AST-02 - duplicate media usually means a template was copied without care.
    if (image.src) {
      if (seen.has(image.src)) {
        findings.push(finding('AST-02', 'The same image file is used more than once.', {
          severity: SEVERITY.warn,
          selector: image.selector,
          detail: image.src.slice(0, 140),
          fix: 'Use a different crop or frame for each slot.',
          where: `${ctx.width}x${ctx.height}`
        }));
      }
      seen.set(image.src, true);
    }

    // AST-01 - photographs carry their provenance.
    const decorative = image.alt === '' && image.rect.width < 80;
    if (!decorative && !image.source) {
      findings.push(finding('AST-01', 'An image has no data-source attribute.', {
        severity: SEVERITY.fail,
        selector: image.selector,
        detail: image.src.slice(0, 140),
        fix: 'Mark the source: client, commissioned, phone, supplier, illustration, library or stand-in.',
        where: `${ctx.width}x${ctx.height}`
      }));
    } else if (image.source && !VALID_SOURCES.has(image.source)) {
      findings.push(finding('AST-01', `Unknown data-source value "${image.source}".`, {
        severity: SEVERITY.fail,
        selector: image.selector,
        fix: `Use one of: ${[...VALID_SOURCES].join(', ')}.`,
        where: `${ctx.width}x${ctx.height}`
      }));
    }
    if (image.source && LIBRARY_SOURCES.has(image.source) && !image.subject) {
      findings.push(finding('AST-01', 'A library image has no data-subject.', {
        severity: SEVERITY.warn,
        selector: image.selector,
        fix: 'Describe the subject so a reviewer can verify the licence and fit.',
        where: `${ctx.width}x${ctx.height}`
      }));
    }
  }

  // AST-03 - one credits line when library photography is used.
  const usesLibrary = facts.images.some(image => LIBRARY_SOURCES.has(image.source));
  if (usesLibrary) {
    const credits = await ctx.page.evaluate(() => {
      const text = document.body.innerText || '';
      const links = [...document.querySelectorAll('a[href]')].map(anchor => anchor.getAttribute('href') || '');
      return {
        line: /(photo|image|asset)s?\s+(credit|licen[cs]e)/i.test(text) || /credits?/i.test(text),
        link: links.some(href => /credit/i.test(href))
      };
    }).catch(() => ({ line: false, link: false }));
    if (!credits.line && !credits.link) {
      findings.push(finding('AST-03', 'Library photography is used but the page has no credits line.', {
        severity: SEVERITY.fail,
        selector: 'footer',
        fix: 'Add one footer line linking to credits.html, generated by assets.mjs photos credits.',
        where: `${ctx.width}x${ctx.height}`
      }));
    }
  }

  // Inline SVG icons need a decorative or labelled role.
  const bareSvgs = await ctx.page.evaluate(() => {
    const out = [];
    for (const svg of document.querySelectorAll('svg')) {
      const labelled = svg.getAttribute('role') === 'img' && (svg.querySelector('title') || svg.getAttribute('aria-label'));
      const decorative = svg.getAttribute('aria-hidden') === 'true' || svg.getAttribute('focusable') === 'false';
      const insideLabelled = svg.closest('a, button')?.innerText?.trim();
      if (!labelled && !decorative && !insideLabelled) {
        out.push(svg.id ? `#${CSS.escape(svg.id)}` : svg.outerHTML.slice(0, 60));
      }
    }
    return out.slice(0, 6);
  }).catch(() => []);
  for (const svg of bareSvgs) {
    findings.push(finding('AST-02', 'An inline SVG has no accessible role.', {
      severity: SEVERITY.warn,
      selector: svg,
      fix: 'Add aria-hidden="true" for decoration, or role="img" plus a <title> for meaning.',
      where: `${ctx.width}x${ctx.height}`
    }));
  }

  return findings;
}
